// Command substrate is the builder: validate a manifest, generate its wiring
// file, build the binary. `go build` of generated output works without it.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hollis-labs/substrate/catalog"
	"github.com/hollis-labs/substrate/manifest"
)

const usage = `substrate <command> [flags]

  validate -f substrate.yaml            check the manifest against the catalogue
  modules  -f substrate.yaml            print the resolved module list
  generate -f substrate.yaml [-pkg main] write substrate_wiring.go next to the manifest
  build    -f substrate.yaml [-o out]   generate, then go build the manifest's directory
  frontend -f substrate.yaml [-o dir]   write frontend.manifest.json: the selected modules' UI contributions and BOM-pinned kits
  upgrade [-dir .] [-to vX.Y.Z] [-dry-run] [-allow-unmigrated]
                                        move an app to another Substrate release: report pin
                                        changes, apply migrations, verify, restore on failure
  pins check|sync [--root .] [--folio dir|file|url] [--app dir]
                                        verify or rewrite go.mod, the CI workflow and
                                        Folio's platform-pins.yaml from bom/bom.yaml
`

func main() {
	if len(os.Args) < 2 {
		fmt.Fprint(os.Stderr, usage)
		os.Exit(2)
	}
	cmd, args := os.Args[1], os.Args[2:]
	if cmd == "pins" {
		pins(args)
		return
	}
	if cmd == "upgrade" {
		upgradeCmd(args)
		return
	}
	fs := flag.NewFlagSet(cmd, flag.ExitOnError)
	file := fs.String("f", "substrate.yaml", "manifest path")
	pkg := fs.String("pkg", "main", "package name of the generated wiring file")
	out := fs.String("o", "", "build output path")
	_ = fs.Parse(args)

	m, err := manifest.Load(*file)
	if err != nil {
		fail(err)
	}
	switch cmd {
	case "validate":
		if errs := m.Validate(); len(errs) > 0 {
			for _, e := range errs {
				fmt.Fprintln(os.Stderr, e)
			}
			os.Exit(1)
		}
		fmt.Println("ok")
	case "modules":
		mods, err := m.Resolve()
		if err != nil {
			fail(err)
		}
		fmt.Println(strings.Join(mods, "\n"))
	case "generate":
		if _, err := generate(m, *file, *pkg); err != nil {
			fail(err)
		}
	case "frontend":
		dir := *out
		if dir == "" {
			dir = filepath.Dir(*file)
		}
		if err := writeFrontend(m, filepath.Dir(*file), dir); err != nil {
			fail(err)
		}
	case "build":
		dir := filepath.Dir(*file)
		if _, err := generate(m, *file, *pkg); err != nil {
			fail(err)
		}
		bin := *out
		if bin == "" {
			bin = filepath.Join(dir, m.App)
		}
		abs, _ := filepath.Abs(bin)
		c := exec.Command("go", "build", "-o", abs, ".")
		c.Dir, c.Stdout, c.Stderr = dir, os.Stdout, os.Stderr
		if err := c.Run(); err != nil {
			fail(err)
		}
	default:
		fmt.Fprint(os.Stderr, usage)
		os.Exit(2)
	}
}

func fail(err error) { fmt.Fprintln(os.Stderr, "substrate:", err); os.Exit(1) }

// generate writes substrate_wiring.go: blank imports of the selected modules
// plus constants. Excluded modules are simply never imported, so never linked.
func generate(m *manifest.Manifest, manifestPath, pkg string) (string, error) {
	mods, err := m.Resolve()
	if err != nil {
		return "", err
	}
	cfg, err := json.Marshal(m.Config)
	if err != nil {
		return "", fmt.Errorf("config must be JSON-compatible: %w", err)
	}
	var imports []string
	for _, n := range mods {
		c, _ := catalog.Find(n)
		imports = append(imports, c.Import)
	}
	sort.Strings(imports)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by substrate from substrate.yaml; DO NOT EDIT.\n\npackage %s\n\nimport (\n", pkg)
	for _, i := range imports {
		fmt.Fprintf(&b, "\t_ %q\n", i)
	}
	fmt.Fprintf(&b, ")\n\nconst (\n\tsubstrateApp = %q\n\tsubstrateConfigJSON = %q\n)\n\n", m.App, string(cfg))
	fmt.Fprintf(&b, "// substrateModules is the start order.\nvar substrateModules = []string{")
	for i, n := range mods {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", n)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", err
	}
	path := filepath.Join(filepath.Dir(manifestPath), "substrate_wiring.go")
	return path, os.WriteFile(path, src, 0o644)
}
